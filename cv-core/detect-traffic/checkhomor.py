import cv2
import numpy as np

# ============================================================
# VIDEO
# ============================================================

VIDEO_PATH = "test/testvd3.mp4"

# ============================================================
# SRC POINTS
# ============================================================

SRC_PTS = np.float32([
    [180, 200],
    [460, 200],
    [580, 500],
    [60, 500]
])

# ============================================================
# LOAD VIDEO
# ============================================================

cap = cv2.VideoCapture(VIDEO_PATH)

ret, frame = cap.read()
frame = cv2.resize(
        frame,
        (640, 640)
    )
if not ret:
    print("Không đọc được video")
    exit()

# ============================================================
# COPY FRAME
# ============================================================

draw = frame.copy()

# ============================================================
# VẼ CÁC ĐIỂM
# ============================================================

for i, (x, y) in enumerate(SRC_PTS):

    x = int(x)
    y = int(y)

    # vẽ điểm
    cv2.circle(
        draw,
        (x, y),
        6,
        (0, 0, 255),
        -1
    )

    # số thứ tự
    cv2.putText(
        draw,
        str(i + 1),
        (x + 10, y - 10),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.8,
        (0, 255, 0),
        2
    )

# ============================================================
# VẼ KHUNG
# ============================================================

pts = SRC_PTS.astype(np.int32)

cv2.polylines(
    draw,
    [pts],
    isClosed=True,
    color=(255, 0, 0),
    thickness=2
)

# ============================================================
# SHOW
# ============================================================

print("Nhan ESC de thoat")

while True:

    cv2.imshow(
        "SRC_PTS Preview",
        draw
    )

    key = cv2.waitKey(1)

    if key == 27:
        break

# ============================================================
# END
# ============================================================

cap.release()

cv2.destroyAllWindows()